import { getModelForClass, modelOptions, prop } from '@typegoose/typegoose';
import { User } from '@/http/nodegen/interfaces';

/**
 * The `users` collection is created and written by Better Auth (see src/services/AuthService.ts):
 * sign up inserts the document, the unique email index is managed by the library.
 * This model is the application's read/update view of the same documents, so field names
 * must stay in step with the Better Auth user schema plus its additionalFields.
 */
@modelOptions({
  schemaOptions: {
    collection: 'users',
    timestamps: true,
    versionKey: false,
  },
})
export class UserClass implements User {
  // UUID string generated by Better Auth (advanced.database.generateId)
  @prop({ type: String })
  _id!: string;

  @prop({ required: true })
  email!: string;

  @prop({ required: true, default: false })
  emailVerified!: boolean;

  @prop()
  name?: string;

  @prop()
  image?: string;

  @prop({ required: true })
  firstName!: string;

  @prop({ required: true })
  lastName!: string;

  @prop({ type: () => [String], required: true, default: [] })
  roles!: string[];

  // Timestamps handled automatically by timestamps: true
  public createdAt!: Date;
  public updatedAt!: Date;
}

export const UserModel = getModelForClass(UserClass);
